"""BibTeX normalization, citation-key generation, and metadata fallback."""

from __future__ import annotations

import re
import unicodedata
from typing import Any, Iterable

from .matching import normalize_title
from .models import Candidate, HeadingEntry

_HEADER_RE = re.compile(r"^(\s*@[A-Za-z]+\s*\{\s*)([^,\s{}]+)(\s*,)", re.DOTALL)
_AUTHOR_LINE_RE = re.compile(r"^\s*author\s*=\s*(.+?)\s*,?\s*$", re.IGNORECASE)
_ARXIV_DOI_RE = re.compile(r"10\.48550/arxiv\.([^/?#]+)", re.IGNORECASE)
_ARXIV_URL_RE = re.compile(r"arxiv\.org/(?:abs|pdf)/([^/?#]+?)(?:\.pdf)?(?:[?#].*)?$", re.IGNORECASE)

_STOPWORDS = {
    "a",
    "an",
    "and",
    "are",
    "as",
    "at",
    "be",
    "by",
    "can",
    "do",
    "does",
    "for",
    "from",
    "how",
    "in",
    "into",
    "is",
    "it",
    "not",
    "of",
    "on",
    "or",
    "the",
    "their",
    "through",
    "to",
    "toward",
    "towards",
    "using",
    "via",
    "what",
    "when",
    "why",
    "with",
}


def ascii_slug(value: str) -> str:
    """Lowercase ASCII slug suitable for a BibTeX citation key."""

    normalized = unicodedata.normalize("NFKD", value)
    normalized = "".join(char for char in normalized if not unicodedata.combining(char))
    normalized = normalized.casefold()
    return re.sub(r"[^a-z0-9]+", "", normalized)


def rewrite_citation_key(bibtex: str, key: str) -> str:
    """Replace the key generated by Crossref with our deterministic key."""

    text = bibtex.strip().lstrip("\ufeff").strip()
    match = _HEADER_RE.match(text)
    if not match:
        raise ValueError("BibTeX response does not start with an entry header")
    text = f"{match.group(1)}{key}{match.group(3)}" + text[match.end() :]
    return text.rstrip() + "\n"


_PAGES_RE = re.compile(r"(?i)(\bpages\s*=\s*\{)([^{}]*)(\})")
_BARE_MONTH_RE = re.compile(r"(?i)(\bmonth\s*=\s*)([A-Za-z]{3,9})(\s*[,}])")


def normalize_crossref_bibtex(bibtex: str, key: str) -> str:
    """Rewrite the key and make publisher BibTeX friendlier to classic BibTeX."""

    text = rewrite_citation_key(bibtex, key)
    # Crossref uses Unicode en/em dashes in page ranges; BibTeX expects "--".
    text = _PAGES_RE.sub(
        lambda match: (
            match.group(1)
            + match.group(2).replace("\u2013", "--").replace("\u2014", "--")
            + match.group(3)
        ),
        text,
    )
    # Crossref may emit "month=Jan"; brace it so it is a literal, not a macro.
    text = _BARE_MONTH_RE.sub(r"\1{\2}\3", text)
    return text


def extract_first_author(bibtex: str) -> str | None:
    """Best-effort extraction of the first author from a BibTeX entry."""

    for line in bibtex.splitlines():
        match = _AUTHOR_LINE_RE.match(line)
        if not match:
            continue
        value = match.group(1).strip()
        if value.startswith("{") and value.endswith("}"):
            value = value[1:-1]
        elif value.startswith('"') and value.endswith('"'):
            value = value[1:-1]
        first = re.split(r"\s+and\s+", value, maxsplit=1, flags=re.IGNORECASE)[0]
        # Crossref may wrap corporate authors in braces.
        first = first.strip().strip("{}").strip()
        return first or None
    return None


def first_author_from_work(work: dict[str, Any]) -> str | None:
    """Return the first author's display name from an OpenAlex work."""

    authorships = work.get("authorships") or []
    if not isinstance(authorships, list):
        return None
    for authorship in authorships:
        if not isinstance(authorship, dict):
            continue
        author = authorship.get("author") or {}
        name = author.get("display_name") or authorship.get("raw_author_name")
        if name:
            return str(name)
    return None


def _family_name(author: str | None) -> str:
    if not author:
        return "anon"
    name = author.strip()
    if "," in name:
        family = name.split(",", 1)[0]
    else:
        family = name.split()[-1] if name.split() else name
    slug = ascii_slug(family)
    if not slug or slug[0].isdigit():
        return "anon"
    return slug


def make_citation_key(
    first_author: str | None,
    year: int | None,
    title: str,
    used_keys: set[str],
) -> str:
    """Create a readable, collision-free key such as ``su2026failure``."""

    family = _family_name(first_author)
    year_part = str(year) if year else "nd"
    words = [
        word
        for word in normalize_title(title).split()
        if word not in _STOPWORDS and len(word) > 1
    ]
    title_part = words[0] if words else "untitled"
    base = f"{family}{year_part}{title_part}"
    base = re.sub(r"[^a-z0-9]+", "", base) or "ref"

    if base not in used_keys:
        used_keys.add(base)
        return base

    suffix = 1
    while True:
        if suffix <= 26:
            candidate = f"{base}{chr(ord('a') + suffix - 1)}"
        else:
            candidate = f"{base}{suffix}"
        if candidate not in used_keys:
            used_keys.add(candidate)
            return candidate
        suffix += 1


def _escape(value: str) -> str:
    value = value.replace("\\", "\x00")
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "#": r"\#",
        "_": r"\_",
        "$": r"\$",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    for char, replacement in replacements.items():
        value = value.replace(char, replacement)
    return value.replace("\x00", "\\")


def _field(name: str, value: Any, *, escape: bool = True) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    if not text:
        return None
    if escape:
        text = _escape(text)
    return f"  {name} = {{{text}}},"


def _extract_arxiv_id(work: dict[str, Any], doi: str | None) -> str | None:
    if doi:
        match = _ARXIV_DOI_RE.search(doi)
        if match:
            return match.group(1)

    urls: list[str] = []
    for location in [work.get("primary_location") or {}] + list(work.get("locations") or []):
        if not isinstance(location, dict):
            continue
        for key in ("landing_page_url", "pdf_url"):
            if location.get(key):
                urls.append(str(location[key]))
    for url in urls:
        match = _ARXIV_URL_RE.search(url)
        if match:
            return match.group(1)
    return None


def construct_bibtex(
    work: dict[str, Any],
    candidate: Candidate,
    entry: HeadingEntry,
    key: str,
) -> str:
    """Build a conservative BibTeX entry when DOI negotiation is unavailable."""

    location = candidate.location or {}
    source = location.get("source") or {}
    source_name = candidate.source_name
    source_type = candidate.source_type
    work_type = candidate.work_type
    doi = candidate.doi
    year = candidate.year or entry.year
    title = str(work.get("title") or work.get("display_name") or entry.title)

    is_journal = source_type == "journal" or work_type in {"article", "review"}
    arxiv_id = _extract_arxiv_id(work, doi)

    if arxiv_id:
        entry_type = "misc"
    elif candidate.is_formal and is_journal:
        entry_type = "article"
    elif candidate.is_formal:
        entry_type = "inproceedings"
    else:
        entry_type = "misc"

    fields: list[str] = []
    authors = [
        str((authorship.get("author") or {}).get("display_name") or "").strip()
        for authorship in (work.get("authorships") or [])
        if isinstance(authorship, dict)
    ]
    authors = [author for author in authors if author]
    if authors:
        fields.append(_field("author", " and ".join(authors)))

    fields.append(_field("title", title))

    if entry_type == "article":
        fields.append(_field("journal", source_name))
    elif entry_type == "inproceedings":
        fields.append(_field("booktitle", source_name))
    elif arxiv_id:
        fields.append(_field("howpublished", "arXiv"))
    elif source_name:
        fields.append(_field("howpublished", source_name))

    fields.append(_field("year", year))

    biblio = work.get("biblio") or {}
    if isinstance(biblio, dict):
        fields.append(_field("volume", biblio.get("volume")))
        fields.append(_field("number", biblio.get("issue")))
        first_page = biblio.get("first_page")
        last_page = biblio.get("last_page")
        if first_page and last_page and first_page != last_page:
            pages = f"{first_page}--{last_page}".replace("\u2013", "--").replace("\u2014", "--")
            fields.append(_field("pages", pages, escape=False))
        elif first_page:
            fields.append(_field("pages", first_page, escape=False))

    publisher = source.get("host_organization_name")
    if publisher and candidate.is_formal:
        fields.append(_field("publisher", publisher))

    if doi:
        fields.append(_field("doi", doi, escape=False))
    url = location.get("landing_page_url") or (f"https://doi.org/{doi}" if doi else work.get("id"))
    fields.append(_field("url", url, escape=False))

    if arxiv_id:
        fields.append(_field("eprint", arxiv_id, escape=False))
        fields.append(_field("archivePrefix", "arXiv"))

    lines = [f"@{entry_type}{{{key},"]
    lines.extend(field for field in fields if field)
    lines.append("}")
    return "\n".join(lines) + "\n"


def merge_entries(bibtex_entries: Iterable[str]) -> str:
    """Join independent BibTeX entries with one blank line between entries."""

    entries = [entry.strip() for entry in bibtex_entries if entry and entry.strip()]
    return "\n\n".join(entries) + ("\n" if entries else "")
