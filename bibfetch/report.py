"""Write the merged BibTeX file, JSON report, and missing-entry report."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

from .models import Issue, ResolvedEntry


def _entry_dict(resolved: ResolvedEntry) -> dict[str, Any]:
    entry = resolved.entry
    candidate = resolved.candidate
    data: dict[str, Any] = {
        "line": entry.line_no,
        "raw_heading": entry.raw_heading,
        "year": entry.year,
        "venue": entry.venue,
        "title": entry.title,
        "status": "found" if resolved.found else "missing",
        "citation_key": resolved.citation_key,
        "bibtex_source": resolved.bibtex_source,
        "bibtex": resolved.bibtex,
        "issues": [
            {
                "code": issue.code,
                "message": issue.message,
                "severity": issue.severity,
            }
            for issue in resolved.issues
        ],
    }
    if candidate is not None:
        data.update(
            {
                "openalex_id": candidate.openalex_id,
                "doi": candidate.doi,
                "matched_title": candidate.work.get("title") or candidate.work.get("display_name"),
                "matched_year": candidate.year,
                "source_name": candidate.source_name,
                "source_type": candidate.source_type,
                "work_type": candidate.work_type,
                "is_formal": candidate.is_formal,
                "is_preprint": candidate.is_preprint,
                "venue_match": candidate.venue_match,
                "title_similarity": round(candidate.title_similarity, 4),
                "score": round(candidate.score, 4),
            }
        )
    return data


def bibtex_header(
    input_path: Path,
    *,
    total: int,
    found: int,
    generated_at: str,
) -> str:
    """Human-readable provenance for the merged bibliography."""

    lines = [
        "% Generated by bibfetch",
        f"% Source: {input_path}",
        f"% Generated: {generated_at}",
        f"% Entries: {found}/{total} found",
    ]
    if found < total:
        lines.append(f"% WARNING: {total - found} entries were not found; see the .missing.txt report")
    return "\n".join(lines) + "\n\n"


def write_bibtex(path: Path, body: str, *, input_path: Path, total: int, found: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    generated_at = datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")
    header = bibtex_header(
        input_path,
        total=total,
        found=found,
        generated_at=generated_at,
    )
    path.write_text(header + body, encoding="utf-8")


def write_json_report(
    path: Path,
    *,
    input_path: Path,
    output_path: Path,
    resolved_entries: Iterable[ResolvedEntry],
    global_issues: Iterable[Issue],
    total_headings: int,
) -> None:
    resolved = list(resolved_entries)
    found = sum(1 for entry in resolved if entry.found)
    payload = {
        "generated_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "input": str(input_path),
        "output": str(output_path),
        "summary": {
            "headings": total_headings,
            "entries": len(resolved),
            "found": found,
            "missing": len(resolved) - found,
        },
        "issues": [
            {"code": issue.code, "message": issue.message, "severity": issue.severity}
            for issue in global_issues
        ],
        "entries": [_entry_dict(entry) for entry in resolved],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def write_missing_report(path: Path, resolved_entries: Iterable[ResolvedEntry]) -> int:
    """Write unresolved entries; remove a stale report when everything matched."""

    missing = [entry for entry in resolved_entries if not entry.found]
    if not missing:
        try:
            path.unlink()
        except FileNotFoundError:
            pass
        return 0

    lines = [f"# Missing BibTeX entries ({len(missing)})", ""]
    for resolved in missing:
        entry = resolved.entry
        lines.append(f"- line {entry.line_no}: {entry.year}. {entry.venue}. {entry.title}")
        for issue in resolved.issues:
            if issue.severity == "error":
                lines.append(f"  reason [{issue.code}]: {issue.message}")
        lines.append("")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return len(missing)
